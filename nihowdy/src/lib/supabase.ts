import { createClient } from '@supabase/supabase-js'

export const supabase = createClient(
  import.meta.env.VITE_SUPABASE_URL,
  import.meta.env.VITE_SUPABASE_ANON_KEY
)

// Call this after Auth0 login to attach the JWT
export function createAuthenticatedClient(auth0Token: string) {
  return createClient(
    import.meta.env.VITE_SUPABASE_URL,
    import.meta.env.VITE_SUPABASE_ANON_KEY,
    { global: { headers: { Authorization: `Bearer ${auth0Token}` } } }
  )
}